export const coerceBreakdownArray = (
  breakdown: unknown,
): DashboardContentStatBreakdown[] | undefined => {
  if (!breakdown) return undefined;
  if (Array.isArray(breakdown)) {
    return breakdown.filter(
      (item): item is DashboardContentStatBreakdown =>
        typeof item === 'object' &&
        item !== null &&
        'label' in item &&
        'value' in item,
    );
  }
  return undefined;
};

